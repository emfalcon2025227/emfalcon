export const getPropertyTypeLabel = (typeValue: string, lang: "ar" | "en" = "ar"): string => {
  const match = PROPERTY_TYPES_CONFIG.find(
    (t) => t.value === typeValue || t.value === typeValue.toUpperCase()
  );
  if (match) return lang === "ar" ? match.nameAr : match.nameEn;

  // Fallback for legacy values
  if (typeValue === "RESIDENTIAL") return lang === "ar" ? "سكني" : "Residential";
  if (typeValue === "COMMERCIAL") return lang === "ar" ? "تجاري" : "Commercial";
  if (typeValue === "MIXED") return lang === "ar" ? "سكني تجاري" : "Mixed";

  return typeValue;
};

export const getPropertyTypeBadgeVariant = (typeValue: string): "info" | "purple" | "warning" | "emerald" | "amber" | "neutral" => {
  const match = PROPERTY_TYPES_CONFIG.find(
    (t) => t.value === typeValue || t.value === typeValue.toUpperCase()
  );
  if (match) return match.badgeColor;
  if (typeValue === "RESIDENTIAL") return "info";
  if (typeValue === "COMMERCIAL") return "purple";
  if (typeValue === "MIXED") return "warning";
  return "neutral";
};
