export const getPermissionDefinition = (permissionId: string): PermissionDefinition | undefined => {
  const normalized = LEGACY_PERMISSION_MAP[permissionId] || permissionId;
  return PERMISSION_REGISTRY.find((p) => p.permissionId === normalized);
};

export const isLegacyMappedPermission = (idA: string, idB: string): boolean => {
  if (idA === idB) return true;
  const mappedA = LEGACY_PERMISSION_MAP[idA] || idA;
  const mappedB = LEGACY_PERMISSION_MAP[idB] || idB;
  return mappedA === mappedB;
};
